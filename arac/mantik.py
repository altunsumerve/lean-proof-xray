#!/usr/bin/env python3
"""Mantık haritası / Logic map — adlandırılmış önermeler arasında "hangi önerme hangilerinden çıkıyor".

TR: Dökümdeki her teoremin önermesi "varsayım₁, …, varsayımₙ ⇒ sonuç" biçimine ayrılır (baştaki bağımsız → zinciri).
    Sonucu aynı olan teoremler o önermenin "kanıtlayanları"dır. Kök önermeden başlanır; her önerme için ispatta
    en ağır kanıtlayan seçilir ve varsayımlarına inilir. Yalnızca önermelerin biçimine ve ağırlık sayımına dayanır.
    Not: bir teoremin varsayımı, ispatın başka yerinde o önermenin kanıtlandığını göstermez; kanıtlayan teorem
    dökümde varsa ayrıca yazılır, yoksa "kanıtlayanı dökümde yok" denir.
EN: Which named statement follows from which. Statement shapes and weight counts only.

Kullanım / usage: mantik.py --kok durum --dok dok.jsonl.gz --dil tr --kok-onerme UpperTheory.EveryCharacter --cikti MANTIK.md
"""
import argparse
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import duz  # noqa: E402
import sozel  # noqa: E402

M = {
    "tr": {"bas": "## İspatın mantığı (önermeler arası harita)",
           "not": "Her satır bir önermedir. Altında, onu sonuç olarak veren ve ispatta en ağır olan teorem ile o teoremin varsayımları yer alır. "
                  "Yüzde: ispatın o teoremin altındaki payı. † işareti: dökümdeki 980 teorem arasında önermesi harfi harfine bu olan yok (önerme başka bir biçimde kanıtlanıyor ya da daha küçük bir adımda kalıyor olabilir). Kurallı üretildi (`arac/mantik.py`).",
           "veren": "şunlardan çıkar [`{t}`, {y}]{diger}:", "diger": "; aynı sonucu varsayımla veren {n} teorem daha var",
           "kanit": "ispatta varsayımsız kanıtlanıyor [`{t}`, {y}]",
           "varsayimsiz": "varsayımsız kanıtlanıyor", "yok": "†", "tekrar": "(yukarıda)", "uzun": "(uzun önerme, {n} karakter)"},
    "en": {"bas": "## The logic of the proof (map between statements)",
           "not": "Each line is a statement. Beneath it: the heaviest theorem in the proof that has it as conclusion, and that theorem's hypotheses. "
                  "Percentage: share of the proof under that theorem. The mark † means: none of the 980 theorems in the dump has literally this statement (it may be proved in another form, or in a smaller step). Generated by rule (`arac/mantik.py`).",
           "veren": "follows from [`{t}`, {y}]{diger}:", "diger": "; {n} more theorems give the same conclusion under hypotheses",
           "kanit": "proved without hypotheses in the proof [`{t}`, {y}]",
           "varsayimsiz": "proved without hypotheses", "yok": "†", "tekrar": "(above)", "uzun": "(long statement, {n} characters)"},
}


def yz(a, t, dil):
    if 0 < 100 * a / t < 0.05:
        return "<%0,1" if dil == "tr" else "<0.1%"
    s = f"{100 * a / t:.1f}"
    return f"%{s.replace('.', ',')}" if dil == "tr" else f"{s}%"


def ayir(C, tip):
    """Önerme → (varsayımlar, sonuç) metinleri; baştaki bağımlı bağlayıcı varsa None (parametreli önerme)."""
    C.kullanilan, C.kirpik, C.katlanan = {}, False, {}
    o, V, g = [], [], tip
    while isinstance(g, list) and g and g[0] == "p":
        if g[2] == "c" or C.kullanir(g[4], 0):
            return None
        V.append(C.t(g[3], o))
        o.append(C.ad(g[1], o, g[3], "onerme"))
        g = g[4]
    return V, C.t(g, o)


def uret(K, dok, dil, kok_onerme, en_cok=40, uzun=140):
    S = M[dil]
    D, bag = sozel.yukle(dok)
    C = duz.Duz(bag, dil, katla=sozel.katlama_tablosu(D))
    KN = f"{K}/koni" if os.path.exists(f"{K}/koni/ozet.json") else K
    W, top = {}, 1
    bas = None
    for l in open(f"{KN}/taslar_ust.tsv", encoding="utf-8"):
        p = l.rstrip("\n").split("\t")
        if bas is None:
            bas = p
            continue
        d = dict(zip(bas, p))
        W[d["ad"]] = int(d["alt_agirlik"])
        if d["baskin"] == "<kok>":
            top = max(top, int(d["alt_agirlik"]))
    veren = collections.defaultdict(list)
    for n in sorted(D):
        d = D[n]
        if d["tur"] != "teorem" or n not in W:
            continue
        r = ayir(C, d["tip"])
        if r:
            veren[r[1]].append((W[n], n, r[0]))
    for k in veren:
        veren[k].sort(key=lambda x: (-x[0], x[1]))
    C.kullanilan = {}
    kok = C.t(["c", kok_onerme], [])
    L, gor, say = [S["bas"], "", S["not"], ""], set(), [0]

    def yaz(s, derin):
        gir = "  " * derin
        et = s if len(s) <= uzun else S["uzun"].format(n=len(s))
        if s in gor:
            L.append(f"{gir}- **{et}** {S['tekrar']}")
            return
        gor.add(s)
        say[0] += 1
        vs = veren.get(s)
        if not vs:
            L.append(f"{gir}- **{et}** {S['yok']}")
            return
        # varsayımsız kanıtlayanlar (önermenin ispatta gerçekten kanıtlandığını gösterir) ve en ağır koşullu kanıtlayan
        kosulsuz = [(w, t) for w, t, h in vs if not h]
        kosullu = [(w, t, h) for w, t, h in vs if h]
        ek = ""
        if kosulsuz:
            ek = " — " + S["kanit"].format(t=kosulsuz[0][1], y=yz(kosulsuz[0][0], top, dil))
        L.append(f"{gir}- **{et}**{ek}")
        if not kosullu:
            return
        # en ağır üç koşullu kanıtlayan (payı en az %2 olanlar; hiçbiri yoksa en ağırı)
        sec = [x for x in kosullu[:3] if x[0] * 50 >= top] or kosullu[:1]
        for w, t, hyps in sec:
            kalan = len(kosullu) - len(sec)
            L.append(f"{gir}  - " + S["veren"].format(t=t, y=yz(w, top, dil), diger=S["diger"].format(n=kalan) if kalan > 0 and t == sec[-1][1] else ""))
            for h in hyps:
                if say[0] >= en_cok:
                    return
                yaz(h, derin + 2)

    yaz(kok, 0)
    return L


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--kok", default="durum")
    a.add_argument("--dok", required=True)
    a.add_argument("--dil", default="tr")
    a.add_argument("--kok-onerme", required=True)
    a.add_argument("--en-cok", type=int, default=40)
    a.add_argument("--cikti", required=True)
    A = a.parse_args()
    L = uret(A.kok, A.dok, A.dil, A.kok_onerme, A.en_cok)
    open(A.cikti, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(len(L), "satır")


if __name__ == "__main__":
    main()
