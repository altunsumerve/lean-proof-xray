#!/usr/bin/env python3
"""Sözlük / Glossary — projenin kendi kavramlarını standart kütüphaneye kadar açar ve derinliğini sayar.

TR: Verilen kavramlardan başlayarak dökümdeki tanımları izler. Her kavram için: tanımı (önerme ise düz cümle, değilse
    imza), doğrudan kullandığı proje kavramları, kütüphaneye inene kadarki katman sayısı ve bu yolda gereken farklı
    proje tanımı sayısı. Dökümde bulunmayan tanımlar sayılamadığı için sayılar ALT SINIRDIR ("en az").
    Yapay zekâ yok; aynı girdi aynı çıktıyı verir.
EN: Unfolds the project's own concepts down to the standard library and counts depth. Counts are lower bounds.

Kullanım / usage: sozluk.py --dok dok.jsonl.gz --dil tr --ad A --ad B [--derin 2] --cikti SOZLUK.md
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import duz  # noqa: E402
import sozel  # noqa: E402

