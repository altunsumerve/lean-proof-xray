def sabitler(e, K):
    if isinstance(e, list):
        if e and e[0] == "c":
            K.add(e[1])
        else:
            for x in e[1:]:
                sabitler(x, K)
    return K


class Sozluk:
    def __init__(self, D, kokler=None, adlar=None):
        self.D = D
        # en kesin ayrım: proje bildirimlerinin tam ad listesi (sinama koşusu yazar: proje_adlari.txt.gz)
        self.adlar = None
        if adlar and os.path.exists(adlar):
            import gzip
            with gzip.open(adlar, "rt", encoding="utf-8") as f:
                self.adlar = {x.rstrip("\n") for x in f if x.strip()}
        # projenin kök ad alanları: verilmişse dosyadan (Lean modülündeki bildirimlerin ilk ad bileşenleri), yoksa dökümden
        # önce sonuç klasöründeki proje_kokleri.txt (xray-export yazar), yoksa eski yerleşim
        yanindaki = os.path.join(os.path.dirname(adlar), "proje_kokleri.txt") if adlar else None
        yol = kokler or (yanindaki if yanindaki and os.path.exists(yanindaki) else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "durum", "proje_kokleri.txt"))
        if os.path.exists(yol):
            self.kokler = {x.strip() for x in open(yol, encoding="utf-8") if x.strip()}
            self.dosyadan = True
        else:
            self.kokler = {n.split(".")[0] for n in D}
            self.dosyadan = False
        self.dog, self.kap = {}, {}

    def proje_mi(self, c):
        if self.adlar is not None:
            return c in self.adlar
        p = c.split(".")
        if p[0] == "_private" and "0" in p:      # _private.<modül>.0.<ad>: asıl ad 0'dan sonra
            p = p[p.index("0") + 1:] or p
        if self.dosyadan:
            return p[0] in self.kokler
        return c in self.D or p[0] in self.kokler

    def dogrudan(self, n):
        """n'nin tanımında doğrudan geçen proje sabitleri (yapıysa kurucusunun alanlarındakiler dahil)."""
        if n in self.dog:
            return self.dog[n]
        d = self.D.get(n)
        K = set()
        if d:
            sabitler(d.get("tip"), K)
            sabitler(d.get("govde"), K)
            for k in d.get("kurucular") or []:
                if k in self.D:
                    sabitler(self.D[k].get("tip"), K)
        # yardımcı ispat sabitleri (_proof_) kavram değildir, sayılmaz
        K = sorted(c for c in K if c != n and "_proof_" not in c and self.proje_mi(c) and c not in (d.get("kurucular") or [])) if d else []
        self.dog[n] = K
        return K

    def kapanis(self, n):
        """(katman, kapanıştaki proje tanımları kümesi, dökümde olmayanlar kümesi) — yinelemesiz derinlik öncelikli."""
        if n in self.kap:
            return self.kap[n]
        sira, yigin, gorulen = [], [(n, 0)], {n}
        while yigin:
            u, i = yigin.pop()
            ds = self.dogrudan(u)
            if i < len(ds):
                yigin.append((u, i + 1))
                v = ds[i]
                if v not in gorulen and v not in self.kap:
                    gorulen.add(v)
                    yigin.append((v, 0))
            else:
                sira.append(u)
        for u in sira:
            der, kume, eksik = 0, set(), set()
            if u not in self.D:
                eksik.add(u)
            else:   # yapının kurucusu dökümde yoksa alanları bilinmiyor: eksik sayılır
                for k in self.D[u].get("kurucular") or []:
                    if k not in self.D:
                        eksik.add(k)
            for v in self.dogrudan(u):
                if v in self.kap:
                    dv, kv, ev = self.kap[v]
                    der = max(der, dv + 1)
                    kume |= kv | {v}
                    eksik |= ev
                else:           # döngü (karşılıklı yineleme) ya da henüz hesaplanmamış: yalnızca kendisi sayılır
                    der = max(der, 1)
                    kume.add(v)
            self.kap[u] = (der, kume, eksik)
        return self.kap[n]


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--dok", required=True)
    a.add_argument("--dil", default="tr")
    a.add_argument("--ad", action="append", default=[])
    a.add_argument("--derin", type=int, default=2, help="başlangıç kavramlarından kaç katman aşağı yazılacak")
    a.add_argument("--uzun", type=int, default=700)
    a.add_argument("--alan-uzun", type=int, default=300, help="yapı alanının cümlesi en çok bu kadar karakterse yazılır")
    a.add_argument("--tam", action="store_true", help="başlangıç kavramlarının bütün kapanışını temelden yukarı sırayla yaz")
    a.add_argument("--eksik", help="dökümde bulunmayan tanım adlarını bu dosyaya yaz")
    a.add_argument("--cikti", required=True)
    A = a.parse_args()
    S = M[A.dil]
    D, bag = sozel.yukle(A.dok)
    Z = Sozluk(D)
    C = duz.Duz(bag, A.dil)
    # yazılacak kavramlar: başlangıçlar ve --derin katman altları (genişlik öncelikli, ad sırasıyla)
    sira, gor, katman = [], set(), [n for n in A.ad if n in D]
    for _ in range(A.derin + 1):
        yeni = []
        for n in katman:
            if n in gor:
                continue
            gor.add(n)
            sira.append(n)
            yeni += [c for c in Z.dogrudan(n) if c in D and D[c]["tur"] in ("tanim", "tip")]
        katman = yeni
    if A.tam:
        # bütün kapanış; önce yalnız kütüphaneye dayananlar, sonra onları kullananlar (katman, ad sırasıyla)
        hepsi, eks = set(), set()
        for n in A.ad:
            if n in D:
                der, kume, eksik = Z.kapanis(n)
                hepsi |= kume | {n}
                eks |= eksik
        sira = sorted((x for x in hepsi if x in D and D[x]["tur"] in ("tanim", "tip")), key=lambda x: (Z.kapanis(x)[0], x))
        if A.eksik:
            open(A.eksik, "w", encoding="utf-8").write("".join(x + "\n" for x in sorted(eks)))
    y_ = [S["bas"], "", S["not"], "", S["tablo"], "|---|---|---:|---:|"]
    for n in sira:
        der, kume, eksik = Z.kapanis(n)
        y_.append(f"| {C.kisa(n)} | {S['tur'].get(D[n]['tur'], D[n]['tur'])} | {der} | {len(kume)} |")
    y_.append("")
    for n in sira:
        d = D[n]
        der, kume, eksik = Z.kapanis(n)
        y_.append(S["ozet"].format(k=C.kisa(n), ad=n, tur=S["tur"].get(d["tur"], d["tur"]), d=der, n=len(kume),
                                   eksik=S["eksik"].format(e=len(eksik)) if eksik else ""))
        y_.append("")
        c = duz.tanim_cumlesi(duz.Duz(bag, A.dil), d)
        if c and len(c) <= A.uzun:
            y_.append(f"> {c}")
            y_.append("")
        else:
            C.kullanilan, C.kirpik, C.katlanan = {}, False, {}
            im = C.t(d["tip"], [])
            if len(im) <= 300:
                y_.append(S["imza"].format(s=f"{C.kisa(n)} : {im}"))
                y_.append("")
        kur = D.get((d.get("kurucular") or [None])[0])
        if kur:
            e_, o_, L_ = kur["tip"], [], []
            C3 = duz.Duz(bag, A.dil)
            for _ in range(d.get("parametre", 0)):
                if isinstance(e_, list) and e_[0] == "p":
                    o_.append(C3.ad(e_[1], o_, e_[3]))
                    e_ = e_[4]
            while isinstance(e_, list) and e_[0] == "p":
                L_.append((sozel.temiz(e_[1]), C3.c(e_[3], o_)))
                o_.append(C3.ad(e_[1], o_, e_[3]))
                e_ = e_[4]
            if L_ and len(L_) <= 12:
                y_.append(S["alan"])
                for a_, c_ in L_:
                    y_.append(f"- `{a_}`: {c_ if len(c_) <= A.alan_uzun else '…'}")
                y_.append("")
        if d.get("kurucular") and not kur:
            y_.append(S["alan_yok"])
            y_.append("")
        ds = Z.dogrudan(n)
        y_.append(S["kullanir"].format(z=", ".join(f"`{C.kisa(x)}`" for x in ds[:30]) + (" …" if len(ds) > 30 else "")) if ds else S["yalniz"])
        y_.append("")
    open(A.cikti, "w", encoding="utf-8").write("\n".join(y_) + "\n")
    print(len(sira), "kavram")


if __name__ == "__main__":
    main()
