#!/usr/bin/env python3
"""Boş koşul taraması / Vacuity scan — her zaman doğru olan koşullar ve tek adımla kanıtlanan sonuçlar.

TR: Dökümdeki bildirimlerde şunları sayar (yalnızca biçime bakar, yorum yapmaz):
    (a) önerme değerli tanımlar ki gövdesi, argümanlarına hiç bakmadan `True` sabitidir;
    (b) alanı olmayan önerme-yapıları (kurucusu argümansız);
    (c) ispat terimi tek bir `rfl` / `True.intro` / `trivial` uygulaması olan teoremler (ispatı okunabilenler arasında).
    Her biri için: dökümde onu doğrudan kullanan bildirim sayısı ve bunların ispattaki en ağır payı.
    Bir koşulun boş olması ispatı geçersiz kılmaz (ana teorem koşulsuz doğrulanmıştır); yalnızca o koşulun bir şey sınamadığını gösterir.
EN: Counts always-true conditions, field-less proposition structures and one-step proofs in the dump. Shape only, no interpretation.

Kullanım / usage: bos.py --kok durum --dok durum/dok.jsonl.gz --dil tr --cikti durum/makale/BOS_tr.md
"""
import argparse
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import duz  # noqa: E402
import mantik  # noqa: E402
import sozel  # noqa: E402
import sozluk  # noqa: E402

M = {
    "tr": {"bas": "# Boş koşul taraması",
           "not": "*Kurallı üretildi (`arac/bos.py`). Kapsam: dökümdeki {n} proje bildirimi ({t} tanım/yapı, ispatı okunabilen {i} teorem); projenin tamamı değil. "
                  "\"Kullanan\": dökümde bu adı doğrudan kullanan bildirim sayısı. \"En ağır pay\": bunlar arasında baskınlık ağacında en ağır olanın ispattaki payı "
                  "(yalnız en üst 3000 düğüm için bilinir; bilinmiyorsa —). Bir koşulun boş olması ispatı geçersiz kılmaz: ana teorem koşulsuz doğrulanmıştır. "
                  "Bu tablo yalnızca hangi koşulların hiçbir şey sınamadığını gösterir.*",
           "a": "## A. Argümanlarına bakmadan `True` olan koşullar ({n})", "b": "## B. Alanı olmayan önerme-yapıları ({n})",
           "c": "## C. Tek adımla kanıtlanan teoremler ({n}; ispatı okunabilen {i} teorem içinde)",
           "tablo": "| Ad | Argüman | Kullanan | En ağır kullanan | En ağır pay |", "tablo_c": "| Teorem | Önerme | İspat | Pay |",
           "yok": "(yok)", "fazla": "… ve {n} tane daha."},
    "en": {"bas": "# Vacuity scan",
           "not": "*Generated by rule (`arac/bos.py`). Scope: the {n} project declarations in the dump ({t} definitions/structures, {i} theorems with readable proofs); not the whole project. "
                  "\"Used by\": number of declarations in the dump that use the name directly. \"Heaviest share\": share of the proof under the heaviest of them in the dominator tree "
                  "(known only for the top 3000 nodes; otherwise —). A vacuous condition does not invalidate the proof: the main theorem is verified unconditionally. "
                  "This table only shows which conditions test nothing.*",
           "a": "## A. Conditions that are `True` regardless of their arguments ({n})", "b": "## B. Proposition structures with no fields ({n})",
           "c": "## C. Theorems proved in one step ({n}; among the {i} theorems with readable proofs)",
           "tablo": "| Name | Arguments | Used by | Heaviest user | Heaviest share |", "tablo_c": "| Theorem | Statement | Proof | Share |",
           "yok": "(none)", "fazla": "… and {n} more."},
}
TEK = {"rfl", "Eq.refl", "True.intro", "trivial", "Iff.rfl", "HEq.refl", "le_refl", "le_rfl"}


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--kok", default="durum")
    a.add_argument("--dok", required=True)
    a.add_argument("--dil", default="tr")
    a.add_argument("--en-cok", type=int, default=60)
    a.add_argument("--tum", help="bütün kayıtta gövdesi True olan tanımlar (ayikla.cpp AYIKLA_BOS çıktısı: ad<TAB>argüman sayısı)")
    a.add_argument("--tum-sayi", help="kayıttaki toplam tanım sayısı (gecis1.log'dan)")
    a.add_argument("--cikti", required=True)
    A = a.parse_args()
    S, K, dil = M[A.dil], A.kok, A.dil
    D, bag = sozel.yukle(A.dok)
    Z = sozluk.Sozluk(D, adlar=os.path.join(A.kok, "proje_adlari.txt.gz"))
    P = {n: d for n, d in D.items() if Z.proje_mi(n)}
    C = duz.Duz(bag, dil)
    KN = f"{K}/koni" if os.path.exists(f"{K}/koni/ozet.json") else K
    W, top, bas = {}, 1, None
    for l in open(f"{KN}/taslar_ust.tsv", encoding="utf-8"):
        p = l.rstrip("\n").split("\t")
        if bas is None:
            bas = p
            continue
        d = dict(zip(bas, p))
        W[d["ad"]] = int(d["alt_agirlik"])
        if d["baskin"] == "<kok>":
            top = max(top, int(d["alt_agirlik"]))
    bosA, bosB, tekC = {}, {}, []
    for n in sorted(P):
        d = P[n]
        # gövdesi (λ'lardan sonra) True sabiti olan her tanım bir koşuldur; tipi bir kısaltmayla yazılmış olsa da (örn. GeoP)
        if d["tur"] == "tanim" and d.get("govde") is not None:
            g, k = d["govde"], 0
            while isinstance(g, list) and g and g[0] == "l":
                g, k = g[4], k + 1
            if g == ["c", "True"]:
                bosA[n] = k
        elif d["tur"] == "tip" and duz.sonuc_tipi(d["tip"]) == ["s", "Prop"] and len(d.get("kurucular") or []) == 1:
            kur = D.get(d["kurucular"][0])
            if kur is not None:
                e, k = kur["tip"], 0
                while isinstance(e, list) and e and e[0] == "p":
                    e, k = e[4], k + 1
                # tipin argüman sayısı parametre sayısını aşıyorsa bu bir yapı değil, indisli ailedir (Eq, HEq gibi): sayılmaz
                t, ta = d["tip"], 0
                while isinstance(t, list) and t and t[0] == "p":
                    t, ta = t[4], ta + 1
                # True kütüphanenin kendi sabit önermesidir: sayılmaz
                if k - d.get("parametre", 0) <= 0 and ta == d.get("parametre", 0) and n != "True":
                    bosB[n] = d.get("parametre", 0)
        if d["tur"] == "teorem" and "ispat" in d:
            g = d["ispat"]
            while isinstance(g, list) and g and g[0] == "l":
                g = g[4]
            b = g[1] if isinstance(g, list) and g and g[0] == "a" else g
            if isinstance(b, list) and b and b[0] == "c" and b[1] in TEK:
                # yalnızca argümanlarında başka proje sabiti yoksa "tek adım"
                if not any(Z.proje_mi(c) for c in sozluk.sabitler(g, set())):
                    tekC.append((n, b[1]))
    hedef = set(bosA) | set(bosB)
    kul = collections.defaultdict(set)
    for n, d in P.items():
        K2 = set()
        for alan in ("tip", "govde", "ispat"):
            if d.get(alan) is not None:
                sozluk.sabitler(d[alan], K2)
        for c in K2 & hedef:
            if c != n:
                kul[c].add(n)
    ni = sum(1 for d in P.values() if "ispat" in d)
    L = [S["bas"], "", S["not"].format(n=len(P), t=sum(1 for d in P.values() if d["tur"] in ("tanim", "tip")), i=ni), ""]

    def tablo(B):
        R = sorted(B, key=lambda x: (-max([W.get(u, 0) for u in kul[x]] or [0]), -len(kul[x]), x))
        if not R:
            return [S["yok"], ""]
        T = [S["tablo"], "|---|---:|---:|---|---:|"]
        for x in R[:A.en_cok]:
            us = sorted(kul[x], key=lambda u: (-W.get(u, 0), u))
            eu = us[0] if us else None
            T.append(f"| `{x}` | {B[x]} | {len(us)} | {('`' + eu + '`') if eu else '—'} | {mantik.yz(W[eu], top, dil) if eu in W else '—'} |")
        if len(R) > A.en_cok:
            T.append("")
            T.append(S["fazla"].format(n=len(R) - A.en_cok))
        return T + [""]

    L += [S["a"].format(n=len(bosA)), ""] + tablo(bosA)
    L += [S["b"].format(n=len(bosB)), ""] + tablo(bosB)
    L += [S["c"].format(n=len(tekC), i=ni), ""]
    if tekC:
        tekC.sort(key=lambda x: (-W.get(x[0], 0), x[0]))
        L += [S["tablo_c"], "|---|---|---|---:|"]
        for n, b in tekC[:A.en_cok]:
            c = C.cumle(D[n]["tip"])
            L.append(f"| `{n}` | {c if len(c) <= 160 else '…'} | `{b}` | {mantik.yz(W[n], top, dil) if n in W else '—'} |")
        if len(tekC) > A.en_cok:
            L += ["", S["fazla"].format(n=len(tekC) - A.en_cok)]
    else:
        L.append(S["yok"])
    if A.tum and os.path.exists(A.tum):
        R = [l.rstrip("\n").split("\t") for l in open(A.tum, encoding="utf-8") if l.strip()]
        R = sorted(R)
        bas = {"tr": "## D. Bütün kayıtta gövdesi `True` olan tanımlar ({n}; kayıttaki {t}tanımların tamamı tarandı, kütüphane dahil)",
               "en": "## D. Definitions whose body is `True` in the whole export ({n}; all {t}definitions scanned, library included)"}[dil]
        L += ["", bas.format(n=len(R), t=(A.tum_sayi + " ") if A.tum_sayi else ""), "", {"tr": "| Ad | Argüman |", "en": "| Name | Arguments |"}[dil], "|---|---:|"]
        L += [f"| `{x[0]}` | {x[1]} |" for x in R]
    open(A.cikti, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(len(bosA), len(bosB), len(tekC))


if __name__ == "__main__":
    main()
