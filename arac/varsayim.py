#!/usr/bin/env python3
"""Varsayım sayımı / Hypothesis census — ispat boyunca varsayım olarak taşınan adlandırılmış önermeler.

TR: Dökümdeki teoremlerin varsayımlarında tek başına bir ad olarak geçen her önerme için: kaç teorem onu varsayıyor,
    bunların en ağırının ispattaki payı, önermesi harfi harfine o olan varsayımsız bir teorem dökümde var mı,
    ve tanımının derinliği (sozluk.py; alt sınır). Yalnızca sayım; adların neye işaret ettiği yorumlanmaz.
EN: Named statements carried as hypotheses through the proof: how many theorems assume each, the share of the
    heaviest one, whether an unconditional theorem with literally that statement is in the dump, definition depth.
"""
import argparse
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import duz  # noqa: E402
import mantik  # noqa: E402
import sozel  # noqa: E402
import sozluk  # noqa: E402

M = {
    "tr": {"bas": "# Varsayım olarak taşınan adlandırılmış önermeler",
           "not": "*Kurallı üretildi (`arac/varsayım.py`). Kapsam: dökümdeki {n} teorem (altında en az 1000 bildirim olan adımlar). "
                  "\"Varsayan\": önermeyi varsayım olarak alan teorem sayısı. \"En ağır pay\": bunların en ağırının ispattaki payı. "
                  "\"Kanıt\": önermesi harfi harfine bu olan varsayımsız teorem dökümde varsa adı; yoksa, bir ispat teriminde o varsayımın yerine konan sabit (‡: bu sabit bir teorem ya da bir yapının kurucusu olabilir; kendisi başka varsayımlar taşıyabilir); o da yoksa †. † kanıtlanmadığı anlamına gelmez "
                  "(ana teorem koşulsuz doğrulanmıştır); yalnızca bu kapsamda harfi harfine eşleşen teorem yoktur. Adlar koddaki adlardır; neye işaret ettikleri yorumlanmamıştır.*",
           "sayi": "Toplam {n} adlandırılmış önerme varsayım olarak taşınıyor; {k} tanesinin harfi harfine eşleşen varsayımsız kanıtı bu kapsamda var; {i} tanesi için, ispat terimi okunabilen {ip} adımdan birinde o varsayımın yerine konan sabit bulundu (‡). "
                   "{e} tanesinin tam adında kodun kendi koyduğu \"Published\" ya da \"Literature\" etiketi geçiyor. Aşağıda en ağır {m} tanesi var.",
           "tablo": "| Önerme | Varsayan | En ağır pay | Kanıt | Tanım: katman / proje tanımı (en az) |"},
    "en": {"bas": "# Named statements carried as hypotheses",
           "not": "*Generated by rule (`arac/varsayim.py`). Scope: the {n} theorems in the dump (steps with at least 1000 declarations beneath them). "
                  "\"Assumed by\": number of theorems taking the statement as a hypothesis. \"Heaviest share\": share of the proof under the heaviest of them. "
                  "\"Proof\": name of an unconditional theorem in the dump with literally this statement, if any; otherwise the constant supplied for that hypothesis in some proof term (‡: it may be a theorem or a structure constructor, and may itself carry hypotheses); failing that, †. † does not mean unproved "
                  "(the main theorem is verified unconditionally); only that no literally matching theorem is in this scope. Names are the code's names; what they refer to is not interpreted.*",
           "sayi": "In total {n} named statements are carried as hypotheses; {k} of them have a literally matching unconditional proof in this scope; for {i} more, the constant supplied for that hypothesis was found in one of the {ip} steps whose proof term could be read (‡). "
                   "{e} of them carry the code's own label \"Published\" or \"Literature\" in their full name. The {m} heaviest are listed below.",
           "tablo": "| Statement | Assumed by | Heaviest share | Proof | Definition: layers / project definitions (at least) |"},
}


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--kok", default="durum")
    a.add_argument("--dok", required=True)
    a.add_argument("--dil", default="tr")
    a.add_argument("--en-cok", type=int, default=80)
    a.add_argument("--etiketli", action="store_true", help="yalnız adında Published/Literature geçenler, hepsi, cümleleriyle")
    a.add_argument("--sonuc-tara", help="ayikla.cpp AYIKLA_SONUC çıktısı: bütün kayıtta, önermesi bu adla biten teoremler (hedef<TAB>teorem<TAB>∀ sayısı)")
    a.add_argument("--adlar-yaz", help="taşınan bütün önermelerin tam adlarını bu dosyaya yaz (karsila.cpp girdisi)")
    a.add_argument("--karsila", help="karsila.cpp çıktısı: her önermenin konide nerede kurulduğu (tam grafikten, bütçesiz)")
    a.add_argument("--cikti", required=True)
    A = a.parse_args()
    S, K, dil = M[A.dil], A.kok, A.dil
    D, bag = sozel.yukle(A.dok)
    C = duz.Duz(bag, dil)          # katlama yok: varsayım tam olarak bir sabitse sayılır
    KN = f"{K}/koni" if os.path.exists(f"{K}/koni/ozet.json") else K
    W, top, bas = {}, 1, None
    for l in open(f"{KN}/taslar_ust.tsv", encoding="utf-8"):
        p = l.rstrip("\n").split("\t")
        if bas is None:
            bas = p
            continue
        d = dict(zip(bas, p))
        W[d["ad"]] = int(d["alt_agirlik"])
        if d["baskin"] == "<kok>":
            top = max(top, int(d["alt_agirlik"]))
    varsayan, kanit, nt = collections.defaultdict(list), {}, 0
    for n in sorted(D):
        d = D[n]
        if d["tur"] != "teorem" or n not in W:
            continue
        nt += 1
        g, hs = d["tip"], []
        while isinstance(g, list) and g and g[0] == "p" and g[2] != "c" and not C.kullanir(g[4], 0):
            hs.append(g[3])
            g = g[4]
        for h in hs:
            # yalnız önermeler: (n : ℕ) gibi kullanılmayan nesne argümanı varsayım değildir
            if isinstance(h, list) and h[0] == "c" and h[1] in D and (C.onerme is None or h[1] in C.onerme):
                varsayan[h[1]].append((W[n], n))
        if not hs and isinstance(g, list) and g[0] == "c":
            if g[1] not in kanit or W[n] > kanit[g[1]][0]:
                kanit[g[1]] = (W[n], n)
    # ispat terimlerinden: bir teoremin adlandırılmış varsayımına, onu uygulayan ispatta hangi sabit veriliyor
    import json
    KT = sozel.katlama_tablosu(D)

    def onerme_adi(h):
        if isinstance(h, list) and h and h[0] == "c" and h[1] in D:
            return h[1] if (C.onerme is None or h[1] in C.onerme) else None
        return KT.get(sozel.katla_anahtari(h)) if isinstance(h, list) else None

    saglayan = collections.defaultdict(collections.Counter)

    def gez(e):
        yigin = [e]
        while yigin:
            e = yigin.pop()
            if not isinstance(e, list) or not e:
                continue
            if e[0] == "a" and isinstance(e[1], list) and e[1] and e[1][0] == "c" and e[1][1] in D:
                g, i, args = D[e[1][1]]["tip"], 0, e[2:]
                while isinstance(g, list) and g and g[0] == "p" and i < len(args):
                    ha = onerme_adi(g[3])
                    if ha:
                        x = args[i]
                        bas = x[1] if isinstance(x, list) and x and x[0] == "a" else x
                        if isinstance(bas, list) and bas and bas[0] == "c":
                            saglayan[ha][bas[1]] += 1
                    g = g[4]
                    i += 1
            yigin.extend(x for x in e[1:] if isinstance(x, list))

    ispatli = 0
    for n in sorted(D):
        if "ispat" in D[n]:
            ispatli += 1
            gez(D[n]["ispat"])
    # bütün kayıt taraması: her hedef için en az ∀'li, sonra ada göre ilk teorem
    tara = {}
    if A.sonuc_tara and os.path.exists(A.sonuc_tara):
        for l in open(A.sonuc_tara, encoding="utf-8"):
            p = l.rstrip("\n").split("\t")
            if len(p) == 3:
                tara.setdefault(p[0], []).append((int(p[2]), p[1]))
        for h in tara:
            tara[h].sort()
    if A.adlar_yaz:
        open(A.adlar_yaz, "w", encoding="utf-8").write("".join(x + "\n" for x in sorted(varsayan)))
    # tam grafikten: önerme konide nerede kuruluyor (karsila.cpp). Sınıf adları o dosyadaki "sonuc" sütunudur.
    grafik = {}
    if A.karsila and os.path.exists(A.karsila):
        bk = None
        for l in open(A.karsila, encoding="utf-8"):
            p = l.rstrip("\n").split("\t")
            if bk is None:
                bk = p
                continue
            grafik[p[0]] = dict(zip(bk, p))
    Z = sozluk.Sozluk(D, adlar=os.path.join(A.kok, "proje_adlari.txt.gz"))
    R = sorted(varsayan.items(), key=lambda kv: (-max(kv[1])[0], -len(kv[1]), kv[0]))
    if A.etiketli:
        R = [kv for kv in R if "Published" in kv[0] or "Literature" in kv[0] or "Lit." in kv[0]]
    else:
        R = R[:A.en_cok]
    # kodun kendi etiketlemesi: adında "Published" ya da "Literature" geçen önermeler (yalnızca ad eşleşmesi)
    etiket = sorted(x for x in varsayan if "Published" in x or "Literature" in x or "Lit." in x)
    cumleler = []
    L = [S["bas"], "", S["not"].format(n=nt), "", S["sayi"].format(n=len(varsayan), k=sum(1 for x in varsayan if x in kanit), e=len(etiket), i=sum(1 for x in varsayan if x not in kanit and saglayan.get(x)), ip=ispatli, m=min(A.en_cok, len(varsayan))), "",
         S["tablo"], "|---|---:|---:|---|---:|"]
    for ad, vs in R:
        der, kume, eksik = Z.kapanis(ad)
        if ad in kanit:
            k = f"`{kanit[ad][1]}` ({mantik.yz(kanit[ad][0], top, dil)})"
        elif saglayan.get(ad):
            v = sorted(saglayan[ad].items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
            k = f"`{v}` ‡"
        elif ad in tara:
            k = f"`{tara[ad][0][1]}` ⁑" + ("" if tara[ad][0][0] == 0 else f" (∀×{tara[ad][0][0]})")
        else:
            k = "†"
        gr = grafik.get(ad)
        if gr and ad not in kanit:
            ilk = lambda sut: gr[sut].split(";")[0].split(" (")[0].strip()
            if gr["sonuc"] == "kuruluyor":
                k += {"tr": f" · grafik: kurucusu `{ilk('en_agir_kuran')}` içinde kullanılıyor ({gr['kuran']} yerde)", "en": f" · graph: constructor used inside `{ilk('en_agir_kuran')}` ({gr['kuran']} places)"}[dil]
            elif gr["sonuc"] == "iceride":
                yer = ilk("en_agir_iceride") if gr["en_agir_iceride"] != "-" else ilk("en_agir_kullanan")
                k += {"tr": f" · grafik: onu taşımayan `{yer}` ispatında anılıyor ya da bir taşıyanı kullanılıyor ({int(gr['iceride']) + int(gr['kullanan'])} yerde)",
                      "en": f" · graph: mentioned, or a carrier used, in the proof of `{yer}`, which does not carry it ({int(gr['iceride']) + int(gr['kullanan'])} places)"}[dil]
            elif gr["sonuc"] == "yalniz_tasiyan_kuruyor":
                k += {"tr": f" · grafik: kurucusunu yalnız onu taşıyanlar kullanıyor (`{ilk('en_agir_kuran_t')}`)", "en": f" · graph: constructor used only by carriers (`{ilk('en_agir_kuran_t')}`)"}[dil]
            else:
                k += {"tr": " · grafik: konide bağlanamadı", "en": " · graph: not linked in the cone"}[dil]
        L.append(f"| **{C.kisa(ad)}** `{ad}` | {len(vs)} | {mantik.yz(max(vs)[0], top, dil)} | {k} | {der} / {len(kume)} |")
        if A.etiketli:
            c = duz.tanim_cumlesi(duz.Duz(bag, dil), D[ad]) if D[ad].get("govde") is not None else None
            cumleler.append((C.kisa(ad), c if c and len(c) <= 420 else None))
    if A.etiketli:
        L.append("")
        L.append({"tr": "Kodun yazdığı cümleler (kısa olanlar; uzunlar sözlükte):", "en": "The sentences the code writes (short ones; long ones are in the glossary):"}[dil])
        L.append("")
        for k_, c_ in cumleler:
            if c_:
                L.append(f"- **{k_}**: {c_}")
    if tara:
        acik = [x for x in varsayan if x not in kanit and not saglayan.get(x)]
        b0 = sum(1 for x in acik if x in tara and tara[x][0][0] == 0)
        b1 = sum(1 for x in acik if x in tara and tara[x][0][0] > 0)
        L.insert(5, {"tr": f"Bu iki yolla bağlanamayan {len(acik)} önerme için kaydın tamamı tarandı (⁑): {b0} tanesinin önermesi tam bu olan, hiç ∀/varsayım taşımayan bir teoremi var; "
                           f"{b1} tanesinin yalnızca ∀ ya da varsayım taşıyan teoremi var (sayısı parantezde); {len(acik) - b0 - b1} tanesi için sonucu bu adla biten hiçbir teorem yok (†).",
                     "en": f"For the {len(acik)} statements not linked in these two ways the whole export was scanned (⁑): {b0} have a theorem stating exactly this with no ∀ or hypothesis; "
                           f"{b1} have only theorems that carry ∀ binders or hypotheses (count in brackets); for {len(acik) - b0 - b1} no theorem in the export concludes with this name (†)."}[dil])
        L.insert(6, "")
    if grafik:
        gs = collections.Counter(grafik[x]["sonuc"] for x in varsayan if x in grafik)
        eksik = sum(1 for x in varsayan if x not in grafik)
        L.insert(5, {"tr": f"Tam bağımlılık grafiğinden (`arac/karsila.cpp`; konideki her bildirim tarandı, ispat bütçesi yok): {gs['kuruluyor']} önermenin kurucusu, o önermeyi kendi önermesinde taşımayan bir ispatta kullanılıyor; "
                           f"{gs['iceride']} önerme, onu taşımayan bir ispatta anılıyor ya da onu taşıyan bir bildirim orada kullanılıyor; {gs['yalniz_tasiyan_kuruyor']} önermenin kurucusunu yalnız onu taşıyan bildirimler kullanıyor; "
                           f"{gs['baglanamadi'] + gs['kayitta_yok'] + eksik} önerme konide bağlanamadı. Bu sayım kenarlardan yapılır: bir bildirimin bir önermeyi varsaydığını mı sonuç olarak verdiğini mi ayırmaz.",
                     "en": f"From the full dependency graph (`arac/karsila.cpp`; every declaration of the cone scanned, no proof budget): for {gs['kuruluyor']} statements the constructor is used in a proof that does not carry the statement; "
                           f"{gs['iceride']} are mentioned, or have a carrier used, in a proof that does not carry them; for {gs['yalniz_tasiyan_kuruyor']} the constructor is used only by carriers; "
                           f"{gs['baglanamadi'] + gs['kayitta_yok'] + eksik} could not be linked in the cone. Counted from edges: it does not tell assuming a statement from concluding it."}[dil])
        L.insert(6, "")
    open(A.cikti, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(len(varsayan), "önerme;", sum(1 for x in varsayan if x in kanit), "kanıtı eşleşen")


if __name__ == "__main__":
    main()
